using ps5::demo::Canvas;
using ps5::demo::Color;

constexpr Color rgb(uint32_t r, uint32_t g, uint32_t b) { return static_cast<Color>(0xff000000u | b << 16 | g << 8 | r); }

inline void draw_text(Canvas& cv, unsigned x, unsigned y, const char* s, unsigned scale, Color col, unsigned max_x = 1880) {
    for (; *s && x + 5 * scale <= max_x; s++, x += 6 * scale) {
        char ch = *s >= 'a' && *s <= 'z' ? (char)(*s - 32) : *s;
        if (ch == ' ') continue;
        const Glyph* gl = nullptr;
        for (const Glyph& g : kFont) if (g.c == ch) { gl = &g; break; }
        if (!gl) continue;
        for (unsigned row = 0; row < 7; row++)
            for (unsigned col_i = 0; col_i < 5; col_i++)
                if (gl->rows[row] >> (4 - col_i) & 1) cv.rectangle(x + col_i * scale, y + row * scale, scale, scale, col);
    }
}

